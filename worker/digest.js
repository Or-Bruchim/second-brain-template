// ── Semantic Memory Profile ───────────────────────────────────────────
export async function updateMemoryProfile(env) {
  const repo = env.GITHUB_REPO || 'your-github-username/your-repo-name'
  const branch = env.GITHUB_BRANCH || 'v4'
  const ghHeaders = {
    Authorization: `token ${env.GITHUB_TOKEN}`,
    'User-Agent': 'OrBrainBot',
    Accept: 'application/vnd.github.v3+json',
  }

  let files
  try {
    const listRes = await fetch(
      `https://api.github.com/repos/${repo}/contents/content/inbox?ref=${branch}`,
      { headers: ghHeaders }
    )
    if (!listRes.ok) throw new Error(`GitHub list failed: ${listRes.status}`)
    files = await listRes.json()
  } catch (err) {
    console.error('updateMemoryProfile: failed to list notes', err)
    return null
  }

  const mdFiles = Array.isArray(files)
    ? files.filter(f => f.type === 'file' && f.name.endsWith('.md'))
    : []
  if (mdFiles.length === 0) return null

  // Slugs are timestamp-based, so reverse-alphabetical ≈ newest first
  const recent = mdFiles.sort((a, b) => b.name.localeCompare(a.name)).slice(0, 30)

  const noteTexts = await Promise.all(
    recent.map(async (file) => {
      try {
        const res = await fetch(file.url, { headers: ghHeaders })
        if (!res.ok) return null
        const data = await res.json()
        const raw = decodeGithubContent(data.content)
        const body = raw.replace(/^---[\s\S]*?---\n?/, '').trim().slice(0, 600)
        const titleMatch = raw.match(/^title:\s*["']?(.*?)["']?\s*$/m)
        const title = titleMatch ? titleMatch[1].trim() : file.name
        return `### ${title}\n${body}`
      } catch { return null }
    })
  )

  const notesContent = noteTexts.filter(Boolean).join('\n\n---\n\n')
  if (!notesContent) return null

  const prompt = `You are analyzing a personal knowledge base to build a memory profile.
Here are the ${noteTexts.filter(Boolean).length} most recent notes:

${notesContent}

Extract and return a markdown profile with these exact sections:
## Areas of Interest
## Current Focus
## Tools & Technologies
## People & Organizations
## Last Updated

Be specific and concise. Use bullet points. Write in English.
Base everything strictly on what appears in the notes — do not invent.
For "Last Updated" write today's date: ${new Date().toISOString().slice(0, 10)}`

  let profileBody
  try {
    const r = await env.AI.run('@cf/meta/llama-3.3-70b-instruct-fp8-fast', { prompt, max_tokens: 800 })
    profileBody = (r.response || '').trim()
    if (!profileBody) throw new Error('Empty LLM response')
  } catch (err) {
    console.error('updateMemoryProfile: LLM failed', err)
    return null
  }

  const fullContent = `---\ntitle: Memory Profile\ntags: ["memory", "meta"]\n---\n\n${profileBody}\n`

  try {
    await commitFile('content/memory/profile.md', fullContent, 'memory: update profile', env, false, false)
  } catch (err) {
    console.error('updateMemoryProfile: commit failed', err)
    return null
  }

  try { await env.BRAIN_KV.put('memory_profile_counter', '0') } catch {}
  console.log('updateMemoryProfile: profile updated successfully')
  return profileBody
}

export async function handleMemoryRefresh(request, env) {
  const secret = request.headers.get('X-Chat-Passphrase')
  if (!env.CHAT_PASSPHRASE || secret !== env.CHAT_PASSPHRASE) {
    return new Response('Unauthorized', { status: 401 })
  }
  const profile = await updateMemoryProfile(env)
  if (!profile) return new Response('Failed to generate profile', { status: 500 })
  return new Response(profile, { headers: { 'Content-Type': 'text/plain; charset=utf-8' } })
}

export async function handleExportCommand(message, env) {
  const chatId = message.chat.id
  const arg = (message.text || '').replace(/^\/export\s*/i, '').trim()

  await sendTelegram(env.TELEGRAM_BOT_TOKEN, chatId, '📦 מכין ייצוא...')

  try {
    if (arg) {
      // Single file: /export notes/foo or /export inbox/2026-...
      const filePath = arg.startsWith('content/') ? arg : `content/${arg}`
      const url = `https://api.github.com/repos/${env.GITHUB_REPO}/contents/${filePath}?ref=${env.GITHUB_BRANCH || 'v4'}`
      const res = await fetch(url, { headers: { Authorization: `Bearer ${env.GITHUB_TOKEN}`, 'User-Agent': 'OrBrainBot' } })
      if (!res.ok) throw new Error(`GitHub ${res.status} for ${filePath}`)
      const data = await res.json()
      const mdContent = atob(data.content.replace(/\n/g, ''))
      const filename = filePath.split('/').pop()
      await sendTelegramDocument(env.TELEGRAM_BOT_TOKEN, chatId, filename, mdContent, `📄 ${filename}`, 'text/plain')
    } else {
      // Full export: all content/**/*.md via tree API
      const treeUrl = `https://api.github.com/repos/${env.GITHUB_REPO}/git/trees/${env.GITHUB_BRANCH || 'v4'}?recursive=1`
      const treeRes = await fetch(treeUrl, { headers: { Authorization: `Bearer ${env.GITHUB_TOKEN}`, 'User-Agent': 'OrBrainBot' } })
      if (!treeRes.ok) throw new Error(`GitHub tree ${treeRes.status}`)
      const treeData = await treeRes.json()
      const mdFiles = (treeData.tree || []).filter(f => f.type === 'blob' && f.path.startsWith('content/') && f.path.endsWith('.md') && !f.path.startsWith('content/templates/'))
      const parts = []
      // Fetch in batches of 10
      for (let i = 0; i < mdFiles.length; i += 10) {
        const batch = mdFiles.slice(i, i + 10)
        const results = await Promise.all(batch.map(async f => {
          try {
            const r = await fetch(`https://api.github.com/repos/${env.GITHUB_REPO}/contents/${f.path}?ref=${env.GITHUB_BRANCH || 'v4'}`, {
              headers: { Authorization: `Bearer ${env.GITHUB_TOKEN}`, 'User-Agent': 'OrBrainBot' },
            })
            if (!r.ok) return null
            const d = await r.json()
            const text = atob(d.content.replace(/\n/g, ''))
            return `<!-- ${f.path} -->\n${text}`
          } catch { return null }
        }))
        parts.push(...results.filter(Boolean))
      }
      const dateStr = new Date().toISOString().slice(0, 10)
      const combined = parts.join('\n\n---\n\n')
      const filename = `brain-export-${dateStr}.md`
      await sendTelegramDocument(env.TELEGRAM_BOT_TOKEN, chatId, filename, combined, `📚 ${mdFiles.length} קבצים`, 'text/plain')
    }
  } catch (err) {
    console.error('handleExportCommand error:', err)
    await sendTelegram(env.TELEGRAM_BOT_TOKEN, chatId, `❌ ייצוא נכשל: ${escapeHtmlTg(err.message)}`, 'HTML')
  }
}

export async function handleStubContextReply(message, env) {
  const chatId = message.chat.id
  const contextText = (message.text || '').trim()
  if (!contextText) return

  try {
    // Get recent inbox files (last 60 min)
    const treeUrl = `https://api.github.com/repos/${env.GITHUB_REPO}/git/trees/${env.GITHUB_BRANCH || 'v4'}?recursive=1`
    const treeRes = await fetch(treeUrl, { headers: { Authorization: `Bearer ${env.GITHUB_TOKEN}`, 'User-Agent': 'OrBrainBot' } })
    if (!treeRes.ok) throw new Error(`GitHub tree ${treeRes.status}`)
    const treeData = await treeRes.json()
    const now = Date.now()
    const inboxFiles = (treeData.tree || [])
      .filter(f => f.type === 'blob' && f.path.startsWith('content/inbox/') && f.path.endsWith('.md'))
      .map(f => {
        const tsMatch = f.path.match(/content\/inbox\/(\d{4}-\d{2}-\d{2})-(\d+)\.md/)
        const ts = tsMatch ? parseInt(tsMatch[2]) : 0
        return { ...f, ts }
      })
      .filter(f => f.ts > 0 && now - f.ts < 60 * 60 * 1000)
      .sort((a, b) => b.ts - a.ts)

    if (!inboxFiles.length) {
      await sendTelegram(env.TELEGRAM_BOT_TOKEN, chatId, '⚠️ לא נמצא לינק שנשמר בשעה האחרונה')
      return
    }

    // Fetch the most recent stub
    const target = inboxFiles[0]
    const fileUrl = `https://api.github.com/repos/${env.GITHUB_REPO}/contents/${target.path}?ref=${env.GITHUB_BRANCH || 'v4'}`
    const fileRes = await fetch(fileUrl, { headers: { Authorization: `Bearer ${env.GITHUB_TOKEN}`, 'User-Agent': 'OrBrainBot' } })
    if (!fileRes.ok) throw new Error(`GitHub ${fileRes.status}`)
    const fileData = await fileRes.json()
    let existing = atob(fileData.content.replace(/\n/g, ''))

    // Add title to frontmatter if missing and append context
    if (!existing.includes('\ntitle:') && existing.startsWith('---')) {
      existing = existing.replace(/^---\n/, `---\ntitle: "${contextText.slice(0, 80)}"\n`)
    }
    if (!existing.trim().endsWith(contextText)) {
      existing = existing.trimEnd() + `\n\n${contextText}\n`
    }
    // Context arrived — clear pending-context so promote.mjs picks the file up
    existing = existing.replace(/^status: pending-context\n/m, '')

    await commitFile(target.path, existing, `inbox: add context to ${target.path.split('/').pop()}`, env, false, false)
    await sendTelegram(env.TELEGRAM_BOT_TOKEN, chatId, `✅ הוספתי את ההערה ל-<code>${target.path.split('/').pop()}</code>`, 'HTML')
  } catch (err) {
    console.error('handleStubContextReply error:', err)
    await sendTelegram(env.TELEGRAM_BOT_TOKEN, chatId, `❌ שגיאה: ${escapeHtmlTg(err.message)}`, 'HTML')
  }
}

// ── Daily digest ───────────────────────────────────────────────────────
export async function sendDailyDigest(env) {
  try {
    const chatIds = env.ALLOWED_CHAT_IDS ? env.ALLOWED_CHAT_IDS.split(',').map(s => s.trim()) : []
    if (!chatIds.length) return

    const now = new Date()
    const israelNow = new Date(now.getTime() + 3 * 3600000)
    const yesterday = new Date(israelNow)
    yesterday.setUTCDate(yesterday.getUTCDate() - 1)
    const yStr = yesterday.toISOString().split('T')[0] // YYYY-MM-DD

    // Fetch yesterday's notes from GitHub
    const branch = env.GITHUB_BRANCH || 'v4'
    const treeRes = await fetch(
      `https://api.github.com/repos/${env.GITHUB_REPO}/git/trees/HEAD?recursive=1`,
      { headers: { Authorization: `Bearer ${env.GITHUB_TOKEN}`, 'User-Agent': 'OrBrainBot' } }
    )
    const treeData = treeRes.ok ? await treeRes.json() : null
    const yesterdayFiles = (treeData?.tree || [])
      .filter(f => f.path.startsWith('content/inbox/') && f.path.includes(yStr) && f.path.endsWith('.md'))
      .slice(0, 10)

    // Fetch today's reminders
    const reminderList = await env.BRAIN_KV.list({ prefix: 'reminder:' })
    const todayStart = new Date(israelNow)
    todayStart.setUTCHours(0, 0, 0, 0)
    const todayEnd = new Date(todayStart.getTime() + 86400000)
    const todayReminders = []
    for (const key of reminderList.keys) {
      const [, tsStr] = key.name.split(':')
      const ts = parseInt(tsStr, 10)
      if (ts >= todayStart.getTime() && ts < todayEnd.getTime()) {
        const val = await env.BRAIN_KV.get(key.name, 'json')
        if (val) todayReminders.push(val)
      }
    }

    // Check if any chatId has a read-later queue (don't skip digest if queue is non-empty)
    let anyQueueItems = false
    if (!yesterdayFiles.length && !todayReminders.length) {
      for (const chatId of chatIds) {
        const q = await env.BRAIN_KV.list({ prefix: `readlater:${chatId}:` }).catch(() => ({ keys: [] }))
        if (q.keys.length) { anyQueueItems = true; break }
      }
      if (!anyQueueItems) return
    }

    const lines = [`☀️ *בוקר טוב!*`] // TODO: personalize with your own name if you want

    if (yesterdayFiles.length) {
      lines.push('', `📥 *נשמר אתמול (${yesterdayFiles.length} פריטים):*`)
      const siteUrl = env.SITE_URL || 'https://your-project.pages.dev'
      // Fetch real titles from each file's frontmatter (parallel)
      const previews = await Promise.all(yesterdayFiles.slice(0, 5).map(async (f) => {
        const slug = f.path.replace('content/', '').replace('.md', '')
        try {
          const res = await fetch(
            `https://api.github.com/repos/${env.GITHUB_REPO}/contents/${f.path}?ref=${branch}`,
            { headers: { Authorization: `Bearer ${env.GITHUB_TOKEN}`, 'User-Agent': 'OrBrainBot' } }
          )
          if (!res.ok) return { slug, title: slug }
          const data = await res.json()
          const md = decodeGithubContent(data.content) || ''
          // Parse title from frontmatter
          const fmMatch = md.match(/^---\s*\n([\s\S]*?)\n---/)
          let title = ''
          if (fmMatch) {
            const titleLine = fmMatch[1].match(/^title:\s*["']?(.+?)["']?\s*$/m)
            if (titleLine) title = titleLine[1].trim()
          }
          // Fallback: first non-frontmatter, non-blockquote line
          if (!title) {
            const body = md.replace(/^---[\s\S]*?\n---\n?/, '').trim()
            const firstLine = body.split('\n').map(l => l.trim()).find(l => l && !l.startsWith('>') && !l.startsWith('#'))
            if (firstLine) title = firstLine.slice(0, 60).replace(/[*_`\[\]]/g, '')
          }
          return { slug, title: title || slug }
        } catch {
          return { slug, title: slug }
        }
      }))
      for (const { slug, title } of previews) {
        lines.push(`  • [${title}](${siteUrl}/${slug})`)
      }
      if (yesterdayFiles.length > 5) lines.push(`  _...ועוד ${yesterdayFiles.length - 5} פריטים_`)
    }

    if (todayReminders.length) {
      lines.push('', `⏰ *תזכורות להיום:*`)
      todayReminders
        .sort((a, b) => new Date(a.scheduledAt) - new Date(b.scheduledAt))
        .forEach(r => {
          const t = new Date(r.scheduledAt).toLocaleTimeString('he-IL', { hour: '2-digit', minute: '2-digit', timeZone: 'Asia/Jerusalem' })
          lines.push(`  • ${t} — ${r.message}`)
        })
    }

    for (const chatId of chatIds) {
      const queueList = await env.BRAIN_KV.list({ prefix: `readlater:${chatId}:` }).catch(() => ({ keys: [] }))
      const queueCount = queueList.keys.length
      const perChat = queueCount
        ? [...lines, '', `📋 *${queueCount} פריט${queueCount !== 1 ? 'ים' : ''} בתור הקריאה — שלח /queue לעיבוד*`]
        : lines
      await sendTelegram(env.TELEGRAM_BOT_TOKEN, chatId, perChat.join('\n'), 'Markdown')
    }
  } catch (err) {
    console.error('sendDailyDigest error:', err)
  }
}

export function fmField(raw, field) {
  const m = raw.match(new RegExp(`^${field}:\\s*["']?(.+?)["']?\\s*$`, 'm'))
  return m?.[1]?.trim() || ''
}

export const WIKI_PATH_RE = /^content\/(notes|projects|meetings|decisions)\/.+\.md$/

export async function sendWeeklyReview(env) {
  try {
    const chatIds = env.ALLOWED_CHAT_IDS ? env.ALLOWED_CHAT_IDS.split(',').map(s => s.trim()) : []
    if (!chatIds.length) return
    const now = new Date()
    const israelNow = new Date(now.getTime() + 3 * 3600000)
    const dates = []
    for (let i = 1; i <= 7; i++) {
      const d = new Date(israelNow)
      d.setUTCDate(d.getUTCDate() - i)
      dates.push(d.toISOString().split('T')[0])
    }
    const treeRes = await fetch(
      `https://api.github.com/repos/${env.GITHUB_REPO}/git/trees/HEAD?recursive=1`,
      { headers: { Authorization: `Bearer ${env.GITHUB_TOKEN}`, 'User-Agent': 'OrBrainBot' } }
    )
    const treeData = treeRes.ok ? await treeRes.json() : null
    const tree = treeData?.tree || []
    const weekFiles = tree.filter(f =>
      f.path.startsWith('content/inbox/') && f.path.endsWith('.md') &&
      dates.some(d => f.path.includes(d))
    )

    // Pending-context stubs: links saved without context, waiting for a reply.
    // Filename starts with the capture date, so scan only the last 30 days of inbox files.
    const cutoff = new Date(israelNow)
    cutoff.setUTCDate(cutoff.getUTCDate() - 30)
    const cutoffStr = cutoff.toISOString().split('T')[0]
    const recentInbox = tree.filter(f => {
      if (!f.path.startsWith('content/inbox/') || !f.path.endsWith('.md')) return false
      const datePart = f.path.replace('content/inbox/', '').slice(0, 10)
      return datePart >= cutoffStr
    })
    const pendingStubs = (await Promise.all(
      recentInbox.map(async f => {
        const raw = await fetchRepoFile(f.path, env)
        if (!/^status:\s*pending-context\s*$/m.test(raw)) return null
        const source = fmField(raw, 'source')
        return { slug: f.path.replace('content/', '').replace('.md', ''), source }
      })
    )).filter(Boolean)

    // Wiki pages created or updated this week (frontmatter date/updated)
    const wikiFiles = tree.filter(f => WIKI_PATH_RE.test(f.path))
    const wikiChanged = (await Promise.all(
      wikiFiles.map(async f => {
        const raw = await fetchRepoFile(f.path, env)
        if (!raw) return null
        const updated = fmField(raw, 'updated') || fmField(raw, 'date')
        if (!dates.includes(updated)) return null
        return { slug: f.path.replace('content/', '').replace('.md', ''), title: fmField(raw, 'title') }
      })
    )).filter(Boolean)

    // Resurface one note from the archive: oldest `updated`, untouched for 21+ days
    const resurfaceCutoff = new Date(israelNow)
    resurfaceCutoff.setUTCDate(resurfaceCutoff.getUTCDate() - 21)
    const resurfaceCutoffStr = resurfaceCutoff.toISOString().split('T')[0]
    let resurfaced = null
    const noteFiles = tree.filter(f => /^content\/notes\/.+\.md$/.test(f.path))
    if (noteFiles.length) {
      const candidates = (await Promise.all(
        noteFiles.map(async f => {
          const raw = await fetchRepoFile(f.path, env)
          if (!raw) return null
          const updated = fmField(raw, 'updated') || fmField(raw, 'date')
          if (!updated || updated > resurfaceCutoffStr) return null
          return { slug: f.path.replace('content/', '').replace('.md', ''), title: fmField(raw, 'title'), updated }
        })
      )).filter(Boolean)
      if (candidates.length) resurfaced = candidates[Math.floor(Math.random() * candidates.length)]
    }

    const siteUrl = env.SITE_URL || 'https://your-project.pages.dev'
    const weekStart = dates[6], weekEnd = dates[0]
    const lines = [
      `📅 <b>סיכום שבועי</b>`,
      `<i>${weekStart} — ${weekEnd}</i>`,
      '',
      `📥 נשמרו <b>${weekFiles.length}</b> פריטים השבוע`,
    ]

    if (weekFiles.length) {
      const noteTexts = await Promise.all(
        weekFiles.slice(0, 20).map(async (file) => {
          const raw = await fetchRepoFile(file.path, env)
          if (!raw) return null
          const title = fmField(raw, 'title') || file.path.split('/').pop()?.replace('.md', '')
          const summary = fmField(raw, 'summary')
          return `- ${title}${summary ? ': ' + summary.slice(0, 100) : ''}`
        })
      )
      const noteList = noteTexts.filter(Boolean).join('\n')
      if (noteList) {
        const prompt = `You are the user's personal assistant. Here are the ${noteTexts.filter(Boolean).length} notes the user saved this week:\n\n${noteList}\n\nWrite a short weekly review in Hebrew (3-5 bullet points):\n• What main themes emerged this week\n• Interesting patterns or connections between topics\n• One suggested follow-up or action\n\nBe specific and personal. No fluff. Under 200 words.`
        const r = await env.AI.run('@cf/meta/llama-3.3-70b-instruct-fp8-fast', { prompt, max_tokens: 400 })
        const insights = (r.response || '').trim()
        if (insights) lines.push('', escapeHtmlTg(insights))
      }
    }

    if (wikiChanged.length) {
      lines.push('', `🧠 <b>הוויקי גדל:</b> ${wikiChanged.length} עמודים נוצרו/עודכנו`)
      for (const w of wikiChanged.slice(0, 5)) {
        lines.push(`  • <a href="${siteUrl}/${w.slug}">${escapeHtmlTg(w.title || w.slug)}</a>`)
      }
    }

    if (pendingStubs.length) {
      lines.push('', `🕗 <b>${pendingStubs.length} לינקים מחכים להקשר:</b>`)
      for (const s of pendingStubs.slice(0, 5)) {
        lines.push(`  • ${escapeHtmlTg(s.source || s.slug)}`)
      }
      lines.push(`  <i>שלח כמה מילים על כל אחד ואתייק אותם</i>`)
    }

    if (resurfaced) {
      lines.push('', `🔄 <b>מהארכיון:</b> <a href="${siteUrl}/${resurfaced.slug}">${escapeHtmlTg(resurfaced.title || resurfaced.slug)}</a> (לא נגעת בו מאז ${resurfaced.updated}) — עדיין רלוונטי?`)
    }

    // Synthesis opportunities from the latest lint report (missing-pages section)
    const lintFiles = tree
      .filter(f => /^content\/lint\/\d{4}-\d{2}-\d{2}\.md$/.test(f.path))
      .map(f => f.path)
      .sort()
    if (lintFiles.length) {
      const lintRaw = await fetchRepoFile(lintFiles[lintFiles.length - 1], env)
      const sectionM = lintRaw.match(/^#+.*(missing|חסר)[^\n]*\n([\s\S]*?)(?=\n#+|\n*$)/im)
      const bullets = (sectionM?.[2] || '')
        .split('\n')
        .filter(l => /^\s*[-*]/.test(l))
        .slice(0, 3)
        .map(l => l.replace(/^\s*[-*]\s*/, '').trim())
        .filter(Boolean)
      if (bullets.length) {
        lines.push('', `🧩 <b>הזדמנויות סינתזה</b> (מתוך ה-lint האחרון):`)
        for (const b of bullets) lines.push(`  • ${escapeHtmlTg(b.slice(0, 120))}`)
        lines.push(`  <i>השב "תבנה עמוד על X" ואטפל בזה</i>`)
      }
    }

    lines.push('', `📝 קיבלת השבוע החלטה ששווה לתעד? כתוב אותה כאן ואתייק אותה כ-decision.`)
    lines.push('', `🔗 <a href="${siteUrl}">פתח את המוח</a>`)
    for (const chatId of chatIds)
      await sendTelegram(env.TELEGRAM_BOT_TOKEN, chatId, lines.join('\n'), 'HTML')
  } catch (err) {
    console.error('sendWeeklyReview error:', err)
  }
}