export function parseFrontmatterForReport(raw, filename) {
  const fmMatch = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)/)
  if (!fmMatch) return null
  const fm = fmMatch[1]
  const get = (key) => { const m = fm.match(new RegExp(`^${key}:\\s*["']?(.*?)["']?\\s*$`, 'm')); return m ? m[1].trim() : '' }
  const tagsMatch = fm.match(/^tags:\s*\[(.+?)\]/m)
  const tags = tagsMatch ? tagsMatch[1].split(',').map(t => t.trim().replace(/["']/g, '')) : []
  return { title: get('title') || filename.replace(/\.md$/, ''), date: get('date'), source: get('source') || 'manual', tags }
}

export function computeReportStats(notes) {
  const SKIP = new Set(['inbox','telegram','chat','manual','link','image','text','pdf','video','youtube','instagram','twitter','docx','note','facebook'])
  const KIND_TAGS = ['image','pdf','docx','text','video','youtube','instagram','twitter','link']
  const sources = {}, kinds = {}, topics = {}, byDay = {}
  for (const n of notes) {
    sources[n.source] = (sources[n.source] || 0) + 1
    const kind = KIND_TAGS.find(k => n.tags.includes(k)) || 'note'
    kinds[kind] = (kinds[kind] || 0) + 1
    for (const t of n.tags) { if (!SKIP.has(t)) topics[t] = (topics[t] || 0) + 1 }
    if (n.date) byDay[n.date] = (byDay[n.date] || 0) + 1
  }
  const dates = notes.map(n => n.date).filter(Boolean).sort()
  const firstDate = dates[0] || '', lastDate = dates[dates.length - 1] || ''
  const totalDays = dates.length > 1 ? Math.max(1, Math.round((new Date(lastDate) - new Date(firstDate)) / 86400000)) : 1
  const avgPerWeek = (notes.length / Math.max(1, totalDays / 7)).toFixed(1)
  const maxDay = Object.entries(byDay).sort((a, b) => b[1] - a[1])[0] || ['', 0]
  return { total: notes.length, firstDate, lastDate, totalDays, avgPerWeek, maxDay, sources, kinds, topics }
}

export async function generateReportInsights(notes, stats, env) {
  const topTopics = Object.entries(stats.topics).sort((a, b) => b[1] - a[1]).slice(0, 6).map(([t, n]) => `${t}(${n})`).join(', ')
  const titles = notes.slice(0, 25).map(n => n.title).join('; ')
  const prompt = `You are analyzing the user's personal knowledge base.

Stats: ${stats.total} notes, ${stats.firstDate} to ${stats.lastDate}. Avg ${stats.avgPerWeek}/week. Most active day: ${stats.maxDay[0]} (${stats.maxDay[1]} notes).
Top topics: ${topTopics}
Sample titles: ${titles}

Write 3-4 bullet points of genuinely insightful observations:
- What themes dominate and what they reveal about the user's focus
- Any notable patterns or shifts over time
- One concrete actionable suggestion

Be specific. No fluff. English only.`
  try {
    const r = await env.AI.run('@cf/meta/llama-3.3-70b-instruct-fp8-fast', { prompt, max_tokens: 350 })
    return (r.response || '').trim()
  } catch { return '' }
}

export function composeReportMarkdown(stats, insights, dateStr) {
  const row = (label, val) => `| ${label} | ${val} |`
  const pct = (n) => `${Math.round(n / stats.total * 100)}%`
  const topTopics = Object.entries(stats.topics).sort((a, b) => b[1] - a[1]).slice(0, 10)
  const topSources = Object.entries(stats.sources).sort((a, b) => b[1] - a[1])
  const topKinds = Object.entries(stats.kinds).sort((a, b) => b[1] - a[1])

  return `---
title: "Brain Report — ${dateStr}"
date: ${dateStr}
tags: ["report", "meta", "analysis"]
---

# 🧠 Brain Report

> Auto-generated on ${dateStr}

## Overview

| Metric | Value |
|--------|-------|
${row('Total notes', stats.total)}
${row('Period', `${stats.firstDate} → ${stats.lastDate} (${stats.totalDays} days)`)}
${row('Avg / week', stats.avgPerWeek)}
${row('Most active day', `${stats.maxDay[0]} (${stats.maxDay[1]} notes)`)}

## Sources

| Source | Notes | % |
|--------|-------|---|
${topSources.map(([s, n]) => `| ${s} | ${n} | ${pct(n)} |`).join('\n')}

## Content Types

| Type | Notes | % |
|------|-------|---|
${topKinds.map(([k, n]) => `| ${k} | ${n} | ${pct(n)} |`).join('\n')}

## Top Topics

| Tag | Count |
|-----|-------|
${topTopics.map(([t, n]) => `| #${t} | ${n} |`).join('\n')}

## 🔍 Insights

${insights || '_No insights generated._'}

---
*Generated by Second Brain Bot*
`
}

export async function generateBrainReport(env) {
  const repo = env.GITHUB_REPO || 'your-github-username/your-repo-name'
  const branch = env.GITHUB_BRANCH || 'v4'
  const ghHeaders = { Authorization: `token ${env.GITHUB_TOKEN}`, 'User-Agent': 'OrBrainBot', Accept: 'application/vnd.github.v3+json' }

  let files
  try {
    const listRes = await fetch(`https://api.github.com/repos/${repo}/contents/content/inbox?ref=${branch}`, { headers: ghHeaders })
    if (!listRes.ok) throw new Error(`GitHub list failed: ${listRes.status}`)
    files = await listRes.json()
  } catch (err) { console.error('generateBrainReport: list failed', err); return null }

  const mdFiles = Array.isArray(files) ? files.filter(f => f.type === 'file' && f.name.endsWith('.md')) : []
  if (!mdFiles.length) return null

  const noteResults = await Promise.all(
    mdFiles.map(async (file) => {
      try {
        const res = await fetch(file.url, { headers: ghHeaders })
        if (!res.ok) return null
        const data = await res.json()
        const raw = decodeGithubContent(data.content)
        return parseFrontmatterForReport(raw, file.name)
      } catch { return null }
    })
  )
  const notes = noteResults.filter(Boolean)
  if (!notes.length) return null

  const stats = computeReportStats(notes)
  const insights = await generateReportInsights(notes, stats, env)
  const dateStr = new Date().toISOString().slice(0, 10)
  const content = composeReportMarkdown(stats, insights, dateStr)
  const slug = `reports/${dateStr}-brain-report`

  try {
    await commitFile(`content/${slug}.md`, content, `report: brain analysis ${dateStr}`, env, false, false)
  } catch (err) { console.error('generateBrainReport: commit failed', err); return null }

  return { content, slug, title: `Brain Report — ${dateStr}` }
}

export async function handleReportGenerate(request, env) {
  const secret = request.headers.get('X-Chat-Passphrase')
  if (!env.CHAT_PASSPHRASE || secret !== env.CHAT_PASSPHRASE) return new Response('Unauthorized', { status: 401 })
  try {
    const result = await generateBrainReport(env)
    if (!result) return jsonResponse({ error: 'Failed to generate report' }, 500)
    const siteUrl = env.SITE_URL || 'https://your-project.pages.dev'
    await triggerDeploy(env)
    return jsonResponse({ ok: true, title: result.title, slug: result.slug, url: `${siteUrl}/${result.slug}` })
  } catch (err) {
    console.error('handleReportGenerate error:', err)
    return jsonResponse({ error: String(err) }, 500)
  }
}

